# Starts normal Beta at Windows logon (per user, no admin). Idempotent: a rerun on an installed
# state changes nothing and says so.
#
# Writes <M3E home>\autostart\beta-logon.cmd and the Startup entry M3E-beta.vbs, which runs it
# without a window. beta-logon.cmd waits until the Neo4j of this device listens on 127.0.0.1:7687
# (up to about 3 minutes; the server refuses to start without its store), then runs
# scripts\beta\launch.bat of this checkout with its output in %TEMP%\m3e-beta-launch.log.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\beta\install-logon-start.ps1
param(
  [string]$M3eHome = $(if ($env:M3E_HOME) { $env:M3E_HOME } else { Join-Path $env:LOCALAPPDATA 'M3E' }),
  [int]$Neo4jPort = 7687,
  [string]$Checkout = (Join-Path $PSScriptRoot '..\..')
)
$ErrorActionPreference = 'Stop'
$checkout = (Resolve-Path $Checkout).Path
if (-not (Test-Path (Join-Path $checkout 'scripts\beta\launch.bat'))) { throw "no scripts\beta\launch.bat in $checkout" }
$autostart = Join-Path $M3eHome 'autostart'
New-Item -ItemType Directory -Force $autostart | Out-Null
$script:changes = 0

function Write-IfChanged($file, [string]$content) {
  $content = ($content -replace "`r?`n", "`r`n").TrimEnd() + "`r`n"
  if ((Test-Path $file) -and ([IO.File]::ReadAllText($file) -eq $content)) { Write-Output "[beta-logon] ok: $(Split-Path $file -Leaf)"; return }
  [IO.File]::WriteAllText($file, $content, (New-Object Text.ASCIIEncoding))
  $script:changes++
  Write-Output "[beta-logon] changed: $(Split-Path $file -Leaf)"
}

$cmdFile = Join-Path $autostart 'beta-logon.cmd'
Write-IfChanged $cmdFile @"
@echo off
REM Generated by scripts/beta/install-logon-start.ps1: start normal Beta at logon.
set "LOG=%TEMP%\m3e-beta-launch.log"
set /a n=0
:wait
netstat -ano | findstr /R /C:"127.0.0.1:$Neo4jPort .*LISTENING" >nul && goto start
set /a n+=1
if %n% GEQ 90 goto start
timeout /t 2 /nobreak >nul
goto wait
:start
REM A Beta still running from an earlier start keeps the log open; then write to a fresh one.
(echo [%DATE% %TIME%] logon start>> "%LOG%") 2>nul || set "LOG=%TEMP%\m3e-beta-launch-%RANDOM%.log"
cd /d "$checkout"
call scripts\beta\launch.bat >> "%LOG%" 2>&1 < nul
"@
Write-IfChanged (Join-Path ([Environment]::GetFolderPath('Startup')) 'M3E-beta.vbs') "CreateObject(""WScript.Shell"").Run ""cmd /c """"$cmdFile"""""", 0, False"
if ($script:changes -eq 0) { Write-Output '[beta-logon] no changes' } else { Write-Output "[beta-logon] $($script:changes) change(s) applied" }
